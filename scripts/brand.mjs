#!/usr/bin/env node
/* S4 Orion brand file (decision 0063): a fixed brand color painted on the first frame.
   A seed's scheme is normally generated in the browser (core.js loads m3color.js, about 100 KB), so a branded page
   paints monochrome for a moment, then turns its color. This writes the same scheme, for light and dark, standard and
   high contrast, as a small CSS file the app links in its <head>, right after orion.css:

     <link rel="stylesheet" href="orion.css">
     <link rel="stylesheet" href="brand.css">

   core.js reads the names the file answers to (--s4-brand) and, when the page's S4.theme seed, variant and surfaces
   match, generates nothing, loads nothing and repaints nothing. It runs the color engine from core.js itself (the block
   between "color-kit:begin" and "color-kit:end"), so the file is exactly what the browser would have written.
   Regenerate it when the brand color changes or after updating Orion.

   Usage: node brand.mjs --seed '#4c7a2a' [--variant auto|fidelity|vibrant|tonal|expressive|…] [--surfaces neutral|tinted] --out brand.css
          (--seed also takes a named accent: blue, indigo, violet, pink, red, orange, amber, green, teal)
   In the repo it reads components/; as the skill's copy it reads ../assets/. No dependencies. */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve } from 'node:path';
import vm from 'node:vm';

const here = dirname(fileURLToPath(import.meta.url));
const first = (...c) => c.map((p) => join(here, p)).find((p) => existsSync(p));
const SRC = {
  core: first('../components/core/core.js', '../assets/orion.js'),
  m3: first('../components/assets/m3color.js', '../assets/m3color.js'),
  css: first('../tokens/tokens.css', '../assets/orion.css'),
};

let engine = null;
function load() {
  if (engine) return engine;
  for (const [k, v] of Object.entries(SRC)) if (!v) throw new Error(`brand.mjs: cannot find ${k} next to ${here}`);
  const core = readFileSync(SRC.core, 'utf8');
  const block = core.slice(core.indexOf('/* color-kit:begin'), core.indexOf('/* color-kit:end'));
  if (!block) throw new Error('brand.mjs: no color-kit block in ' + SRC.core);
  const sandbox = { window: {} };
  vm.runInNewContext(readFileSync(SRC.m3, 'utf8'), sandbox);
  vm.runInNewContext(block + '\nthis.colorKit = colorKit;', sandbox);
  const css = readFileSync(SRC.css, 'utf8');
  const num = (name, d) => { const m = css.match(new RegExp(name + ':\\s*([\\d.]+)')); return m ? +m[1] : d; };   /* the first match is the base (light, standard contrast) value */
  const k = num('--s4-glass-backdrop-contrast-float', 1), br = num('--s4-glass-backdrop-brightness-float', 1);
  const filt = (v) => Math.min(255, Math.max(0, ((v - 127.5) * k + 127.5) * br));
  const glass = { fab: num('--s4-glass-tint-opacity-fab', 0.75), color: num('--s4-glass-tint-opacity-fab-color', 0.9), lo: filt(0), hi: filt(255) };
  const accents = JSON.parse((core.match(/S4\.theme\.accents = (\{[^}]+\})/) || [, '{}'])[1].replace(/'/g, '"').replace(/(\w+):/g, '"$1":'));
  engine = { kit: sandbox.colorKit(sandbox.window.M3Color, glass), glass, accents };
  return engine;
}

/* the CSS for one brand: { seed, variant = 'auto', surfaces = 'neutral' } */
export function brandCss({ seed, variant = 'auto', surfaces = 'neutral' } = {}) {
  const { kit, glass, accents } = load();
  const hex = accents[String(seed).toLowerCase()] || seed;
  if (!/^#[0-9a-f]{6}$/i.test(hex || '')) throw new Error(`brand.mjs: --seed must be a #rrggbb color or a named accent, got ${seed}`);
  if (hex.toLowerCase() === '#000000') throw new Error('brand.mjs: black is the monochrome default; it needs no brand file');
  const cfg = { seed: hex.toLowerCase(), variant, variantSet: variant !== 'auto', surfaces: surfaces === 'tinted' ? 'tinted' : 'neutral' };
  const names = kit.brandKeys(cfg).join(' ');
  return `/* S4 Orion brand: ${cfg.seed}, variant ${variant}, ${cfg.surfaces} surfaces. GENERATED by brand.mjs (decision 0063); do not edit.
   Link it right after orion.css. core.js sees --s4-brand and does not repaint. Regenerate after changing the brand or updating Orion. */
@layer s4.tokens{:where(:root){--s4-brand:"${names}";--s4-brand-floors:"${glass.fab} ${glass.color}"}}
${kit.pageCss(cfg, 0)}
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const arg = (n) => { const i = process.argv.indexOf('--' + n); return i > 0 ? process.argv[i + 1] : undefined; };
  const seed = arg('seed'), out = arg('out');
  if (!seed || !out) { console.error("Usage: node brand.mjs --seed '#4c7a2a' [--variant auto] [--surfaces neutral|tinted] --out brand.css"); process.exit(2); }
  try {
    const css = brandCss({ seed, variant: arg('variant') || 'auto', surfaces: arg('surfaces') || 'neutral' });
    writeFileSync(resolve(out), css);
    console.log(`Wrote ${out} (${(Buffer.byteLength(css) / 1024).toFixed(1)} KB). Link it right after orion.css.`);
  } catch (e) { console.error(e.message); process.exit(1); }
}
