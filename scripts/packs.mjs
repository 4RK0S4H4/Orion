#!/usr/bin/env node
/* The lean app bundle (decision 0069): which packs a page needs, from what the page itself writes.
   `node packs.mjs page.html [--assets dir]` prints the packs the page needs and the link tags to use.
   Library: needsOf(source, index) -> { packs: [...], why: { pack: [reasons] } }, used by scripts/build.mjs (the proof that every
   lean page links what it uses) and by the page checker. index is packs.json, generated by scripts/build.mjs.
   No dependencies; the skill ships a copy of this file next to its assets. */
import { readFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

/* soft needs: a component whose script lends a hand to another's (it checks first, so nothing breaks without it, but a
   feature is lost): doc tabs reorder with the direct-manipulation script. */
export const SOFT = { 'doc-tabs': 'direct' };

export function needsOf(src, index) {
  const packs = new Set(), why = {};
  const add = (p, r) => { packs.add(p); (why[p] = why[p] || new Set()).add(r); };
  const text = src.replace(/<!--[\s\S]*?-->/g, '');
  const tokens = new Set(text.match(/\bs4-[a-z0-9-]+/g) || []);
  for (const [name, p] of Object.entries(index.packs)) {
    for (const c of tokens) if (p.classes.includes(c)) add(name, '.' + c);
    for (const a of new Set(text.match(/\bdata-[a-z0-9-]+/g) || [])) if (p.attrs.includes(a)) add(name, a);
    for (const m of new Set([...text.matchAll(/\bS4\.([A-Za-z]+)/g)].map((x) => x[1]))) if (p.names.includes(m)) add(name, 'S4.' + m);
  }
  for (const p of [...packs]) for (const n of (index.needs || {})[p] || []) add(n, `${p} calls it`);
  for (const [c, to] of Object.entries(SOFT)) if (tokens.has('s4-' + c)) add(to, 'doc tabs reorder with it');
  return { packs: [...packs].sort(), why: Object.fromEntries(Object.entries(why).map(([k, v]) => [k, [...v].slice(0, 6)])) };
}

/* the icon file a lean page loads (issue 109): icons-app.js, the icons the app templates and the lean bundle draw (any
   other name fetches icons-solar.js once), or a single set's file such as icons-phosphor-duotone.js; icons.js holds every
   set and is only for a page that switches sets at run time (S4.icon.use, S4.icon.restore, a data-icons switch) */
export function iconsOf(src) {
  const text = src.replace(/<!--[\s\S]*?-->/g, '');
  const loaded = [...text.matchAll(/(?:^|["'/])(icons(?:-[a-z-]+)?\.js)(?:\?[^"']*)?["']/g)].map((m) => m[1]);
  const switches = /S4\.icon\.(use|restore)\(|data-icons\b/.test(text);
  const want = switches ? 'icons.js' : 'icons-app.js';
  const problem = loaded.length === 0 ? `loads no icon file; load ${want}`
    : loaded.length > 1 ? `loads ${loaded.length} icon files (${loaded.join(', ')}); load one: ${want}`
    : loaded[0] === 'icons.js' && !switches ? 'loads icons.js (every icon set) but never switches sets; load icons-app.js'
    : loaded[0] !== 'icons.js' && switches ? `switches icon sets (S4.icon.use) but loads ${loaded[0]}, which holds one set; load icons.js`
    : null;
  return { want, loaded, switches, problem };
}

/* the packs a page links (orion.<pack>.min.css) */
export function linkedPacks(src, index) {
  const out = new Set();
  for (const m of src.matchAll(/orion\.([a-z]+)\.min\.(?:css|js)/g)) if (m[1] === 'core' || index.packs[m[1]]) out.add(m[1]);
  return out;
}

if (process.argv[1] === fileURLToPath(import.meta.url) && process.argv[2]) {
  const here = dirname(fileURLToPath(import.meta.url));
  const ai = process.argv.indexOf('--assets');
  const dir = ai > 0 ? process.argv[ai + 1] : [join(here, '../assets'), join(here, '../components')].find((d) => existsSync(join(d, 'packs.json')));
  const index = JSON.parse(readFileSync(join(dir, 'packs.json'), 'utf8'));
  const src = readFileSync(process.argv[2], 'utf8');
  const need = needsOf(src, index), have = linkedPacks(src, index);
  console.log(`needs: core${need.packs.map((p) => ' + ' + p).join('')}`);
  for (const p of need.packs) console.log(`  ${p}: ${need.why[p].join(', ')}`);
  console.log('links (CSS in the head after orion.core.min.css, scripts after orion.core.min.js):');
  for (const p of need.packs) console.log(`  <link rel="stylesheet" href="orion.${p}.min.css"> <script src="orion.${p}.min.js"></script>`);
  const ic = iconsOf(src);
  console.log(`icons: <script src="${ic.want}"></script>${ic.switches ? ' (the page switches icon sets)' : ' (any icon it lacks loads icons-solar.js from the same folder)'}`);
  if (ic.problem && /orion\.core\.min\.(css|js)/.test(src)) { console.error(`ICONS: the page ${ic.problem}`); process.exitCode = 1; }
  if (have.size) {
    const miss = need.packs.filter((p) => !have.has(p)), extra = [...have].filter((p) => p !== 'core' && !need.packs.includes(p));
    if (miss.length) { console.error(`MISSING packs: ${miss.join(', ')}`); process.exitCode = 1; }
    if (extra.length) console.log(`unused packs linked: ${extra.join(', ')}`);
  }
}
