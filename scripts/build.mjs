#!/usr/bin/env node
/* Bundle S4 Orion for apps and for the skill.
   - components/orion.css: tokens + base + every component + glass + motion, in the @import order of components/index.css,
     with url()s rewritten for the new location.
   - components/orion.js:  core, motion, then every component's script (same order).
   - skill/s4-orion/assets/: orion.css, orion.js, icons.js, m3color.js, inter-variable.woff2 (the skill ships its own copy).
   Run after npm run build:tokens and build:icons (npm run build does all three). --check fails if any output is stale.
   No dependencies. */
import { readFileSync, writeFileSync, existsSync, mkdirSync, copyFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, relative, posix } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const CHECK = process.argv.includes('--check');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const comp = join(root, 'components');
const entry = readFileSync(join(comp, 'index.css'), 'utf8');
const imports = [...entry.matchAll(/@import url\("([^"]+)"\)/g)].map((m) => m[1]);
const problems = [];

/* ---------- CSS ---------- */
function inlineCss(outDir, fontDir) {
  const parts = [];
  for (const rel of imports) {
    const file = join(comp, rel);
    if (!existsSync(file)) { problems.push(`missing ${relative(root, file)}`); continue; }
    let css = readFileSync(file, 'utf8');
    css = css.replace(/url\("?(?!data:|https?:|#)([^")]+)"?\)/g, (m, u) => {
      const abs = join(dirname(file), u);
      if (fontDir && /\.woff2$/.test(u)) return `url("${posix.join(fontDir, u.split('/').pop())}")`;
      return `url("${relative(outDir, abs).split('\\').join('/')}")`;
    });
    parts.push(`/* ---- ${relative(comp, file)} ---- */\n${css.trim()}\n`);
  }
  return parts;
}
const banner = (what) => `/* S4 Orion ${pkg.version} ${what}. GENERATED by scripts/build.mjs. Do not edit: change tokens/src or components/ and rebuild.
   Inter (SIL OFL 1.1) · Solar icons by 480 Design (CC BY 4.0) · Material Color Utilities (Apache 2.0) */\n`;
const cssRepo = banner('stylesheet') + inlineCss(comp).join('\n');
const cssSkill = banner('stylesheet') + inlineCss(comp, '.').join('\n');

/* ---------- JS ---------- */
const jsOrder = ['core/core.js', 'motion/motion.js'];
for (const rel of imports) {
  const dir = rel.split('/')[0];
  const js = `${dir}/${dir}.js`;
  if (existsSync(join(comp, js)) && !jsOrder.includes(js)) jsOrder.push(js);
}
const js = banner('runtime') + jsOrder.map((f) => `/* ---- ${f} ---- */\n${readFileSync(join(comp, f), 'utf8').trim()}\n`).join('\n');

/* ---------- write ---------- */
const skillAssets = join(root, 'skill/s4-orion/assets');
const outputs = {
  'components/orion.css': cssRepo,
  'components/orion.js': js,
  'skill/s4-orion/assets/orion.css': cssSkill,
  'skill/s4-orion/assets/orion.js': js,
};
/* lighter copies for pages that count every kilobyte (websites, issue 53): the same code, with comments and spare
   whitespace taken out. Deliberately conservative (no parser): CSS keeps every space a selector or calc() could need,
   strings are untouched; JS keeps its line breaks, so automatic semicolons behave exactly as in the original. */
function minCss(css) {
  const keep = [];
  css = css.replace(/"(?:[^"\\\n]|\\.)*"|'(?:[^'\\\n]|\\.)*'/g, (s) => `\u0000${keep.push(s) - 1}\u0000`);
  css = css.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\s+/g, ' ')
    .replace(/\s*([{};])\s*/g, '$1').replace(/;}/g, '}').replace(/,\s+(?=[^{}]*\{)/g, ',').trim();
  return css.replace(/\u0000(\d+)\u0000/g, (m, i) => keep[+i]);
}
function minJs(src) {
  const out = []; let inBlock = false;
  for (let line of src.split('\n')) {
    const t = line.trim();
    if (inBlock) { if (t.includes('*/')) { inBlock = false; const rest = t.slice(t.indexOf('*/') + 2).trim(); if (rest) out.push(rest); } continue; }
    if (t.startsWith('/*')) { if (!t.includes('*/')) inBlock = true; else { const rest = t.slice(t.indexOf('*/') + 2).trim(); if (rest) out.push(rest); } continue; }
    if (!t || t.startsWith('//')) continue;
    out.push(t.replace(/([;{}),])\s+\/\*(?:(?!\*\/)[^'"`])*\*\/$/, '$1'));
  }
  return out.join('\n') + '\n';
}
const minBanner = (what) => `/* S4 Orion ${pkg.version} ${what}, minified. GENERATED by scripts/build.mjs. Inter (SIL OFL 1.1) · Solar icons by 480 Design (CC BY 4.0) · Material Color Utilities (Apache 2.0) */\n`;
outputs['components/orion.min.css'] = minBanner('stylesheet') + minCss(cssRepo);
outputs['components/orion.min.js'] = minBanner('runtime') + minJs(js);
outputs['skill/s4-orion/assets/orion.min.css'] = minBanner('stylesheet') + minCss(cssSkill);
outputs['skill/s4-orion/assets/orion.min.js'] = outputs['components/orion.min.js'];
/* one icon set per file (Horizon 2): a page that never switches sets loads only the set it draws */
{
  const I = JSON.parse(readFileSync(join(comp, 'icons/names.json'), 'utf8'));
  const reg = existsSync(join(comp, 'assets/icons.js')) ? readFileSync(join(comp, 'assets/icons.js'), 'utf8') : '';
  const m = reg.match(/window\.S4_ICONS = (\{[\s\S]*\});\s*$/);
  if (!m) problems.push('components/assets/icons.js: cannot read the icon registry (run npm run build:icons)');
  else {
    const all = JSON.parse(m[1]);
    for (const id of Object.keys(all.sets)) {
      const s = all.sets[id];
      outputs[`components/assets/icons-${id}.js`] = `/* S4 Orion icons, one set: ${s.label}. GENERATED by scripts/build.mjs from components/assets/icons.js. ${s.credit}. Load instead of icons.js when the page never switches sets. */\n` +
        `(function(){var i=${JSON.stringify(s.icons)};window.S4_ICONS={set:${JSON.stringify(id)},viewBox:${JSON.stringify(s.viewBox)},credit:${JSON.stringify(s.credit)},icons:i,sets:{${JSON.stringify(id)}:{label:${JSON.stringify(s.label)},viewBox:${JSON.stringify(s.viewBox)},credit:${JSON.stringify(s.credit)},icons:i}}};})();\n`;
    }
    outputs[`skill/s4-orion/assets/icons-${I.set}.js`] = outputs[`components/assets/icons-${I.set}.js`];
  }
}
/* the demo is a self-contained app that carries its own copy (its font sits beside the stylesheet) so it can never go stale */
import { createHash } from 'node:crypto';
import { readdirSync } from 'node:fs';
const hash = (t) => createHash('sha1').update(t).digest('hex').slice(0, 7);
const demoCss = cssSkill.replace('url("assets/inter-variable.woff2")', 'url("inter-variable.woff2")');
if (existsSync(join(root, 'demo/index.html'))) { outputs['demo/orion.css'] = demoCss; outputs['demo/orion.js'] = js; }
/* cache-busting: every local asset a page loads with ?v=... gets its version from the file's content, so a changed file is a new URL
   and phones never need a hard refresh (the HTML pages themselves are opened through links that carry the commit, see CLAUDE.md) */
const htmlIn = (d) => (existsSync(join(root, d)) ? readdirSync(join(root, d)).filter((f) => f.endsWith('.html')).map((f) => d + '/' + f) : []);
const pages = ['index.html', 'demo/index.html', 'tokens/index.html'].concat(htmlIn('explore'), htmlIn('templates')).filter((f) => existsSync(join(root, f)));
/* brand files (decision 0063): a template with a fixed brand links brand/<name>.css right after its stylesheet; the
   file is written here from the seed, variant and surfaces in its own S4.theme.restore(…) call, by the same engine the
   browser runs (scripts/brand.mjs), so its brand paints on the first frame and the stale check keeps it current */
const { brandCss } = await import('./brand.mjs');
outputs['skill/s4-orion/scripts/brand.mjs'] = readFileSync(join(root, 'scripts/brand.mjs'), 'utf8');
for (const page of htmlIn('templates')) {
  const src = readFileSync(join(root, page), 'utf8'), link = src.match(/href="(brand\/[\w-]+\.css)\?v=/);
  if (!link) continue;
  const call = src.match(/\{[^{}]*\bseed:\s*'#[0-9a-fA-F]{6}'[^{}]*\}/), get = (k) => call && (call[0].match(new RegExp(k + ":\\s*'([^']+)'")) || [])[1];   /* the brand's own object: its S4.theme.restore(…) defaults */
  if (!get('seed')) { problems.push(`${page}: links ${link[1]} but names no seed ({ seed: '#rrggbb', … } in its script)`); continue; }
  outputs['templates/' + link[1]] = brandCss({ seed: get('seed'), variant: get('variant') || 'auto', surfaces: get('surfaces') || 'neutral' });
}
const fileText = (rel) => (rel in outputs ? outputs[rel] : existsSync(join(root, rel)) ? readFileSync(join(root, rel)) : null);
for (const page of pages) {
  const dir = page.includes('/') ? page.slice(0, page.lastIndexOf('/')) : '';
  const src = readFileSync(join(root, page), 'utf8');
  const out = src.replace(/((?:src|href)=")([^"?#:]+)\?v=[\w.-]*(")/g, (m, a, path, c) => {
    const rel = join(dir, path).split('\\').join('/'), t = fileText(rel);
    return t == null ? m : a + path + '?v=' + hash(t) + c;
  });
  if (out !== src) outputs[page] = out;
}
const copies = {
  'skill/s4-orion/assets/icons.js': 'components/assets/icons.js',
  'skill/s4-orion/assets/m3color.js': 'components/assets/m3color.js',
  'skill/s4-orion/assets/inter-variable.woff2': 'components/assets/inter-variable.woff2',
  'demo/icons.js': 'components/assets/icons.js',
};
/* ---------- templates: starter pages for each kind of app, copied into the skill with flat asset paths ---------- */
for (const page of htmlIn('templates')) {
  const name = page.split('/').pop();
  if (name === 'index.html') continue;
  const src = page in outputs ? outputs[page] : readFileSync(join(root, page), 'utf8');
  outputs['skill/s4-orion/templates/' + name] = src
    .replace(/(?:\.\.\/components\/(?:assets\/)?)([\w.-]+)\?v=[\w.-]*/g, '$1')
    .replace(/<!-- Template: /, /orion\.min\.css/.test(src)
      ? '<!-- S4 Orion template (copy orion.min.css, orion.min.js, icons-solar.js, m3color.js and inter-variable.woff2 next to it: the lighter files a website loads). '
      : '<!-- S4 Orion template (copy orion.css, orion.js, icons.js, m3color.js and inter-variable.woff2 next to it). ');
}
for (const f of Object.keys(outputs).filter((f) => /^templates\/brand\//.test(f))) outputs['skill/s4-orion/' + f] = outputs[f];
/* ---------- skill references (generated, so they can't drift from the repo) ---------- */
const refs = {};
const GROUPS = [
  ['Actions', ['button', 'icon-button', 'button-group', 'fab']],
  ['Navigation and shell', ['app', 'layout', 'page', 'top-app-bar', 'nav-bar', 'nav-rail', 'tabs', 'toolbar', 'search', 'desktop', 'menubar', 'doc-tabs', 'statusbar', 'commands', 'breadcrumbs', 'pagination', 'stepper']],
  ['Containment and data', ['card', 'pane', 'list', 'table', 'stat', 'meter', 'board', 'description-list', 'divider', 'avatar', 'accordion', 'expand', 'empty-state', 'states', 'direct', 'filter', 'tree', 'chart', 'ring', 'milestones', 'timeline', 'month']],
  ['Content', ['prose', 'message', 'code']],
  ['Websites', ['site']],
  ['Inputs', ['form', 'text-field', 'combobox', 'tag-input', 'number-field', 'code-field', 'upload', 'time-field', 'rating', 'date-picker', 'chip', 'switch', 'checkbox', 'radio', 'slider', 'swatches', 'color-field', 'password', 'inline-edit']],
  ['Feedback', ['badge', 'status', 'progress', 'banner', 'skeleton', 'reward', 'snackbar', 'tooltip']],
  ['Overlays', ['menu', 'dialog', 'sheet', 'palette']],
];
{
  const toc = [], body = [];
  for (const [g, names] of GROUPS) {
    toc.push(`- **${g}:** ` + names.map((n) => `[${n}](#${n})`).join(', '));
    for (const n of names) {
      const f = join(comp, n, 'README.md');
      if (!existsSync(f)) { problems.push(`missing components/${n}/README.md`); continue; }
      const md = readFileSync(f, 'utf8').replace(/^# (.+)$/m, `## $1 {#${n}}`).replace(/^## (?!.*\{#)/gm, '### ').replace(/\]\(\.\.\/([a-z-]+)\/\)/g, '](#$1)');
      body.push(`<a id="${n}"></a>\n\n` + md.replace(/ \{#[a-z-]+\}/, '').trim());
    }
  }
  refs['components.md'] = `# S4 Orion components\n\nGENERATED by scripts/build.mjs from components/*/README.md. Markup, attributes, when to use what, do/don't, accessibility.\nEvery component has a live reference page at https://4rk0s4h4.github.io/s4-orion/components/<name>/<name>.html.\n\n## Contents\n\n${toc.join('\n')}\n\n` + body.join('\n\n---\n\n') + '\n';
}
{
  const T = JSON.parse(readFileSync(join(root, 'tokens/tokens.json'), 'utf8')).tokens;
  const groups = [
    ['Color roles', /^--md-sys-color-/], ['Type scale', /^--md-sys-typescale-/], ['Typefaces', /^--md-ref-typeface-/],
    ['Shape scale', /^--md-sys-shape-corner-/], ['Component shapes', /^--s4-shape-/], ['Spacing', /^--s4-space-/], ['Sizes', /^--s4-size-/],
    ['Layout', /^--s4-layout-/], ['Websites (fluid type, section rhythm, widths)', /^--s4-site-/], ['Breakpoints', /^--s4-breakpoint-/], ['Stacking (z-index)', /^--s4-z-/], ['Elevation', /^--md-sys-elevation-/],
    ['State', /^--md-sys-state-/], ['Focus and scrim', /^--s4-(focus|scrim)-/], ['Motion: springs', /^--(md-sys|s4)-motion-spring-/],
    ['Motion: patterns', /^--s4-motion-pattern-/], ['Glass', /^--s4-glass-/], ['Icons', /^--s4-icon-/]];
  const short = (v) => (v.startsWith('linear(') ? 'linear(…) spring easing' : v);
  const out = ['# S4 Orion tokens', '', 'GENERATED by scripts/build.mjs from tokens/tokens.json (source: tokens/src/*.tokens.json). Use these names; never write the values.',
    'Light values are shown; a second value is dark mode. Color roles also change with the seed at run time. Live: https://4rk0s4h4.github.io/s4-orion/tokens/', ''];
  for (const [g, re] of groups) {
    const names = Object.keys(T).filter((n) => re.test(n) && !/-(stiffness|damping)$/.test(n));
    if (!names.length) continue;
    out.push(`## ${g}`, '', '| Token | Value | Dark | Notes |', '|---|---|---|---|');
    for (const n of names) { const t = T[n]; out.push(`| \`${n}\` | ${short(t.value).replace(/\|/g, '\\|')} | ${t.modes && t.modes.dark ? short(t.modes.dark) : ''} | ${(t.description || '').replace(/\|/g, '\\|')} |`); }
    out.push('');
  }
  refs['tokens.md'] = out.join('\n');
}
{
  const I = JSON.parse(readFileSync(join(comp, 'icons/names.json'), 'utf8'));
  const rows = Object.entries(I.sets[I.set].names).map(([n, src]) => `| \`${n}\` | ${src} |`);
  refs['icons.md'] = `# S4 Orion icon vocabulary\n\nGENERATED by scripts/build.mjs from components/icons/names.json. Use the name in \`<span class="s4-icon" data-icon="name"></span>\`; the second column is the ${I.set} icon it draws today.\nArrows and chevrons are Linear, everything else Bold Duotone. Other sets: ${Object.keys(I.sets).join(', ')} (\`S4.icon.use('phosphor-duotone')\`, optionally with \`{ save: 'app-key' }\`). Unknown names log \`S4: unknown icon\` in the console. Another icon: \`S4.icon.add({ name: '<svg body>' })\`.\n\n| Name | ${I.set} icon |\n|---|---|\n${rows.join('\n')}\n`;
}
for (const f of ['color', 'typography', 'shape', 'spacing', 'elevation', 'motion', 'glass', 'accessibility']) {
  const src = join(root, 'docs/foundations', f + '.md');
  if (!existsSync(src)) { problems.push(`missing docs/foundations/${f}.md`); continue; }
  refs[f + '.md'] = `<!-- GENERATED copy of docs/foundations/${f}.md (scripts/build.mjs). Edit the original. -->\n` + readFileSync(src, 'utf8');
}
for (const [f, c] of Object.entries(refs)) outputs['skill/s4-orion/references/' + f] = c;

if (problems.length) { console.error(problems.map((p) => '  x ' + p).join('\n')); process.exit(1); }
if (CHECK) {
  const stale = Object.entries(outputs).filter(([f, c]) => !existsSync(join(root, f)) || readFileSync(join(root, f), 'utf8') !== c).map(([f]) => f)
    .concat(Object.entries(copies).filter(([to, from]) => !existsSync(join(root, to)) || !readFileSync(join(root, to)).equals(readFileSync(join(root, from)))).map(([f]) => f));
  if (stale.length) { console.error(`Stale bundle (run npm run build): ${stale.join(', ')}`); process.exit(1); }
  console.log(`Bundle up to date: ${imports.length} stylesheets, ${jsOrder.length} scripts.`);
} else {
  mkdirSync(skillAssets, { recursive: true }); mkdirSync(join(root, 'skill/s4-orion/references'), { recursive: true });
  for (const [f, c] of Object.entries(outputs)) { mkdirSync(dirname(join(root, f)), { recursive: true }); writeFileSync(join(root, f), c); }
  for (const [to, from] of Object.entries(copies)) copyFileSync(join(root, from), join(root, to));
  const kb = (s) => (Buffer.byteLength(s) / 1024).toFixed(0) + ' KB';
  console.log(`Built components/orion.css (${kb(cssRepo)}) and orion.js (${kb(js)}) from ${imports.length} stylesheets and ${jsOrder.length} scripts; copied assets to skill/s4-orion/assets/`);
}
