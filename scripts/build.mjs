/* lighter copies for pages that count every kilobyte (websites, issue 53): the same code, with comments and spare
   whitespace taken out. Deliberately conservative (no parser): CSS keeps every space a selector or calc() could need,
   strings are untouched; JS keeps its line breaks, so automatic semicolons behave exactly as in the original. */
function minCss(css) {
  const keep = [];
  css = css.replace(/"(?:[^"\\\n]|\\.)*"|'(?:[^'\\\n]|\\.)*'/g, (s) => `\u0000${keep.push(s) - 1}\u0000`);
  css = css.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\s+/g, ' ')
    .replace(/\s*([{};])\s*/g, '$1').replace(/;}/g, '}').replace(/,\s+(?=[^{}]*\{)/g, ',').trim();
  return css.replace(/\u0000(\d+)\u0000/g, (m, i) => keep[+i]);
}
function minJs(src) {
  const out = []; let inBlock = false;
  for (let line of src.split('\n')) {
    const t = line.trim();
    if (inBlock) { if (t.includes('*/')) { inBlock = false; const rest = t.slice(t.indexOf('*/') + 2).trim(); if (rest) out.push(rest); } continue; }
    if (t.startsWith('/*')) { if (!t.includes('*/')) inBlock = true; else { const rest = t.slice(t.indexOf('*/') + 2).trim(); if (rest) out.push(rest); } continue; }
    if (!t || t.startsWith('//')) continue;
    out.push(t.replace(/([;{}),])\s+\/\*(?:(?!\*\/)[^'"`])*\*\/$/, '$1'));
  }
  return out.join('\n') + '\n';
}
