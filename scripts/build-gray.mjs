/* Gray temperature (decision 0055). Orion's neutral base is pure gray; an app may ask for a warm or a cool one:
     <html data-gray="warm">   or   S4.theme({ gray: 'warm' })
   This script reads the standard-contrast light and dark blocks of tokens/tokens.css, takes every pure gray color role
   and gives it a little chroma at the same OKLCH lightness, and writes components/base/gray.css. White and black stay
   white and black (chroma falls to zero at both ends), so the page is still "Crisper" (0045).
   Proof: the script fails if any color's luminance, as a contrast ratio sees it (L + 0.05), moves by more than 1%, so every contrast pair the
   token check proved for the pure grays still holds. High-contrast modes keep the pure grays.
   node scripts/build-gray.mjs [--check] */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'components/base/gray.css');
const css = readFileSync(join(root, 'tokens/tokens.css'), 'utf8');

const TEMPS = { warm: { hue: 75, chroma: 0.011 }, cool: { hue: 255, chroma: 0.011 } };

/* sRGB <-> OKLCH */
const lin = (c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
const gam = (c) => (c <= 0.0031308 ? 12.92 * c : 1.055 * c ** (1 / 2.4) - 0.055);
const lum = ([r, g, b]) => 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b);
function oklchToRgb(L, C, h) {
  const a = C * Math.cos((h * Math.PI) / 180), b = C * Math.sin((h * Math.PI) / 180);
  const l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3, m = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3, s = (L - 0.0894841775 * a - 1.291485548 * b) ** 3;
  return [4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s, -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s, -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s]
    .map((v) => Math.min(1, Math.max(0, gam(v))));
}
const hex = (rgb) => '#' + rgb.map((v) => Math.round(v * 255).toString(16).padStart(2, '0')).join('');

let worst = 0;
function tint(gray, t) {
  const v = parseInt(gray.slice(1, 3), 16) / 255;
  const L = Math.cbrt(lin(v));                                  /* OKLab lightness of a pure gray */
  const C = t.chroma * Math.min(1, (1 - L) * 14, L * 9);        /* none at white and black, full in between */
  /* hold the WCAG luminance: nudge L until the tinted color is as bright as the gray it replaces */
  let lo = 0, hi = 1, rgb;
  for (let i = 0; i < 30; i++) { const mid = (lo + hi) / 2; rgb = oklchToRgb(mid, C, t.hue); if (lum(rgb) < lin(v)) lo = mid; else hi = mid; }
  rgb = hex(rgb).match(/\w\w/g).map((x) => parseInt(x, 16) / 255);
  const drift = Math.abs(lum(rgb) - lin(v)) / (lin(v) + 0.05);   /* as a contrast ratio sees it: (L + 0.05) */
  worst = Math.max(worst, drift);
  return hex(rgb);
}

/* the declarations of one block of tokens.css, found by the line that opens it */
function block(open) {
  const i = css.indexOf(open);
  if (i < 0) throw new Error('build-gray: block not found: ' + open);
  return css.slice(i + open.length, css.indexOf('}', i));
}
function grays(body, t) {
  const lines = [];
  for (const m of body.matchAll(/(--md-sys-color-[a-z-]+|--s4-color-control[a-z-]*):\s*(#[0-9a-f]{6})\s*;/g)) {
    const [, name, value] = m;
    if (!(value.slice(1, 3) === value.slice(3, 5) && value.slice(3, 5) === value.slice(5, 7))) continue;   /* pure grays only */
    const v = tint(value, t);
    if (v !== value) lines.push(`${name}: ${v};`);
  }
  return lines;
}
const light = block('  :where(:root) {');
const dark = block('  :where([data-theme="dark"]) {');

let o = `/* GENERATED by scripts/build-gray.mjs from tokens/tokens.css. Do not edit.
   Gray temperature (decision 0055): data-gray="warm" | "cool" on <html>, or S4.theme({ gray }). Pure gray is the default.
   Same lightness as the pure grays, so every proven contrast pair holds; high contrast keeps the pure grays. */
@layer s4.tokens {
`;
for (const [name, t] of Object.entries(TEMPS)) {
  const L = grays(light, t), D = grays(dark, t), sel = `:root[data-gray="${name}"]:not([data-contrast="high"])`;
  const body = (lines, pad) => lines.map((l) => pad + l).join('\n');
  o += `  @media not (prefers-contrast: more) {
    :where(${sel}) {
${body(L, '      ')}
    }
    @media (prefers-color-scheme: dark) {
      :where(${sel}:not([data-theme="light"])) {
${body(D, '        ')}
      }
    }
    :where(${sel}[data-theme="dark"]) {
${body(D, '      ')}
    }
  }
`;
}
/* Scoped (issue 52): data-gray on any element, nearest one wins (@scope proximity), and it reaches the light or dark
   scopes inside it. Each role is light-dark(light, dark), so the mode is whatever color-scheme that element has. A
   container may also say data-gray="pure" to go back to the pure grays inside a warm or cool page. */
const pureOf = (body) => Object.fromEntries([...body.matchAll(/(--md-sys-color-[a-z-]+|--s4-color-control[a-z-]*):\s*(#[0-9a-f]{6})\s*;/g)].map((m) => [m[1], m[2]]));
const PL = pureOf(light), PD = pureOf(dark);
const NOT_HC = ':root:not([data-contrast="high"])';
const scopedSel = `:where(${NOT_HC} :scope, ${NOT_HC} :scope [data-theme], :scope${NOT_HC.slice(5)}:root [data-theme])`;
const tinted = Object.fromEntries(Object.entries(TEMPS).map(([name, t]) => {
  const L = Object.fromEntries(grays(light, t).map((l) => l.slice(0, -1).split(': '))), D = Object.fromEntries(grays(dark, t).map((l) => l.slice(0, -1).split(': ')));
  return [name, { L, D }];
}));
const allNames = [...new Set(Object.values(tinted).flatMap(({ L, D }) => [...Object.keys(L), ...Object.keys(D)]))];
o += '  @media not (prefers-contrast: more) {\n';
for (const [name, { L, D }] of [...Object.entries(tinted), ['pure', { L: {}, D: {} }]]) {
  const names = name === 'pure' ? allNames : [...new Set([...Object.keys(L), ...Object.keys(D)])];
  o += `    @scope ([data-gray="${name}"]) {\n      ${scopedSel} {\n`;
  const ld = (n) => `light-dark(${L[n] || PL[n]}, ${D[n] || PD[n]})`;
  o += names.map((n) => `        ${n}: ${ld(n)};`).join('\n') + '\n';
  /* the glass tints are written plainly in a light or dark scope (tokens.css), so the gray scope gives them its own */
  o += `        --s4-glass-tint-float: ${ld('--md-sys-color-surface-container')};\n        --s4-glass-tint-fill: ${ld('--md-sys-color-surface-container-highest')};\n      }\n    }\n`;
}
o += '  }\n';
o += '}\n';

if (worst > 0.01) { console.error(`build-gray: luminance drift ${(worst * 100).toFixed(2)}% is over 1%`); process.exit(1); }
if (process.argv.includes('--check')) {
  if (!existsSync(out) || readFileSync(out, 'utf8') !== o) { console.error('Stale gray.css (run npm run build)'); process.exit(1); }
  console.log(`Gray temperatures up to date: warm and cool, worst luminance drift ${(worst * 100).toFixed(2)}% (1% allowed).`);
} else {
  writeFileSync(out, o);
  console.log(`Built components/base/gray.css: warm and cool, worst luminance drift ${(worst * 100).toFixed(2)}%.`);
}
